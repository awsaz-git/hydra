-- Onboarding: the athlete profile, the user's preferences, and their consent to the privacy policy.
-- Measurements are always stored in one unit (kg, cm, seconds); the preferences only change how
-- the app shows and reads them (FEATURE-PLAN 10.3, D23).
-- Never edit this file once it has run on staging or production; add a new migration instead.

-- +goose Up

CREATE TABLE profiles (
    user_id            uuid         PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    -- 16+ is checked in Go (services/onboarding.go): a CHECK using today's date would give a
    -- different answer on another day, e.g. when a backup is restored.
    birth_date         date         NOT NULL CHECK (birth_date > DATE '1900-01-01'),
    sex                text         NOT NULL CHECK (sex IN ('male', 'female')),
    height_cm          numeric(4,1) NOT NULL CHECK (height_cm BETWEEN 100 AND 250),
    weight_kg          numeric(5,2) NOT NULL CHECK (weight_kg BETWEEN 30 AND 300),

    -- 1 to 3 groups from the list, one of them the main one (D15: profile lists are JSONB).
    athlete_groups     jsonb        NOT NULL CHECK (
        jsonb_typeof(athlete_groups) = 'array'
        AND jsonb_array_length(athlete_groups) BETWEEN 1 AND 3
        AND athlete_groups <@ '["strength", "physique", "endurance", "hybrid", "sport", "combat", "tactical", "general"]'::jsonb
    ),
    main_group         text         NOT NULL CHECK (athlete_groups ? main_group),

    -- Best recent set of each lift: weight and reps both given, or both empty ("I don't do this lift").
    squat_kg           numeric(5,2) CHECK (squat_kg BETWEEN 1 AND 500),
    squat_reps         smallint     CHECK (squat_reps BETWEEN 1 AND 15),
    bench_kg           numeric(5,2) CHECK (bench_kg BETWEEN 1 AND 500),
    bench_reps         smallint     CHECK (bench_reps BETWEEN 1 AND 15),
    deadlift_kg        numeric(5,2) CHECK (deadlift_kg BETWEEN 1 AND 500),
    deadlift_reps      smallint     CHECK (deadlift_reps BETWEEN 1 AND 15),
    CHECK ((squat_kg IS NULL) = (squat_reps IS NULL)),
    CHECK ((bench_kg IS NULL) = (bench_reps IS NULL)),
    CHECK ((deadlift_kg IS NULL) = (deadlift_reps IS NULL)),

    -- Best endurance result: a distance and a time, or neither.
    endurance_distance text         CHECK (endurance_distance IN ('5k', '10k', 'half', 'full')),
    endurance_seconds  integer      CHECK (endurance_seconds > 0),
    CHECK ((endurance_distance IS NULL) = (endurance_seconds IS NULL)),

    created_at         timestamptz  NOT NULL DEFAULT now(),
    updated_at         timestamptz  NOT NULL DEFAULT now()
);

-- How the app shows things to this user. Onboarding sets the units from one metric/imperial
-- choice; picking each unit separately comes with the settings page.
CREATE TABLE preferences (
    user_id             uuid        PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    language            text        NOT NULL CHECK (language IN ('en')),
    theme               text        NOT NULL CHECK (theme IN ('hydra-dark')),
    weight_unit         text        NOT NULL CHECK (weight_unit IN ('kg', 'lb')),
    distance_unit       text        NOT NULL CHECK (distance_unit IN ('km', 'mi')),
    short_distance_unit text        NOT NULL CHECK (short_distance_unit IN ('m', 'yd')),
    height_unit         text        NOT NULL CHECK (height_unit IN ('cm', 'ft_in')),
    energy_unit         text        NOT NULL CHECK (energy_unit IN ('kcal', 'kj')),
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now()
);

-- Which version of the privacy policy a user agreed to, and when: one row per version, so the
-- record of what was agreed stays (FEATURE-PLAN 11.5). The version is the policy's date.
CREATE TABLE consents (
    id             bigint      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id        uuid        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    policy_version text        NOT NULL CHECK (policy_version ~ '^\d{4}-\d{2}-\d{2}$'),
    consented_at   timestamptz NOT NULL DEFAULT now(),
    UNIQUE (user_id, policy_version)
);

-- Row-level security, like every user-owned table (00002).
ALTER TABLE profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE preferences ENABLE ROW LEVEL SECURITY;
ALTER TABLE consents ENABLE ROW LEVEL SECURITY;

CREATE POLICY profiles_own_row ON profiles
    USING (user_id = NULLIF(current_setting('app.user_id', true), '')::uuid)
    WITH CHECK (user_id = NULLIF(current_setting('app.user_id', true), '')::uuid);
CREATE POLICY preferences_own_row ON preferences
    USING (user_id = NULLIF(current_setting('app.user_id', true), '')::uuid)
    WITH CHECK (user_id = NULLIF(current_setting('app.user_id', true), '')::uuid);
CREATE POLICY consents_own_rows ON consents
    USING (user_id = NULLIF(current_setting('app.user_id', true), '')::uuid)
    WITH CHECK (user_id = NULLIF(current_setting('app.user_id', true), '')::uuid);

-- A consent is a record of what was agreed: it can be added, never changed or removed on its
-- own. It goes when the account does (the foreign-key cascade runs with the owner's rights).
REVOKE UPDATE, DELETE ON consents FROM hydra_app;

-- +goose Down

DROP TABLE consents;
DROP TABLE preferences;
DROP TABLE profiles;
