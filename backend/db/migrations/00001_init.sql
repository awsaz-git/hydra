-- The first schema: chats and their messages (what AutoMigrate used to create).
-- Never edit this file once it has run on staging or production; add a new migration instead.

-- +goose Up

-- hydra_app must not touch goose's own bookkeeping table (roles.sql gives it row access
-- to every new table by default, and goose creates this one before running migrations).
REVOKE ALL ON goose_db_version FROM hydra_app;
REVOKE ALL ON SEQUENCE goose_db_version_id_seq FROM hydra_app;

CREATE TABLE conversations (
    id         uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    title      text        NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE messages (
    id              bigint      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    conversation_id uuid        NOT NULL REFERENCES conversations (id) ON DELETE CASCADE,
    role            text        NOT NULL CHECK (role IN ('user', 'assistant')),
    content         text        NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_messages_conversation_id ON messages (conversation_id);

